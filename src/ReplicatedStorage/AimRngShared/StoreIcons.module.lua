function StoreIcons.CardFor(e: any): any
    if type(e) ~= "table" or not e.Cat or not e.Id then return nil end
    return StoreIcons.Card[e.Cat .. ":" .. tostring(e.Id)]
end

-- the stage image for an entry's detail panel (its set's), or nil
function StoreIcons.StageFor(e: any): string?
    if type(e) ~= "table" then return nil end
    if e.Cat == "Bundle" then
        local s = StoreIcons.BundleSet[e.Id]
        return s and StoreIcons.Stage[s] or nil
    end
    local c = StoreIcons.CardFor(e)
    return c and c.Set and StoreIcons.Stage[c.Set] or nil
end

