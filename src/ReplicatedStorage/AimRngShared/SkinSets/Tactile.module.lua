local function TcDotSeq(lit)
    -- a row of TC_DOTS soft dots (a gradient's transparency: dot / gap / dot ...), the first `lit` full, the rest dim
    local kp = {}
    local n = TC_DOTS * 2 - 1
    for i = 0, n do
