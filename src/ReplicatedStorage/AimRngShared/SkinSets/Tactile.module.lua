        local dot = math.floor(i / 2) + 1
        local tr = isDot and ((dot <= lit) and 0 or 0.65) or 1
        table.insert(kp, NumberSequenceKeypoint.new(i / n, tr))
    end
    return NumberSequence.new(kp)
end
