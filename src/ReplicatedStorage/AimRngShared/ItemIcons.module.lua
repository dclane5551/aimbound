local function gunSpec(id: string): any?
    local i = gunIndex[id]
    if not i then return nil end
    local a = (i - 1) // PER_ATLAS + 1
    local img = ItemIcons.ATLAS[a]
    if not img or img == "" then return nil end
    local c = (i - 1) % PER_ATLAS
    local off = Vector2.new((c % 3) * GW, (c // 3) * GH)
    local t = ItemIcons.TIGHT[id] or { 0, 0, GW, GH }
    return { Image = img, RectOffset = off, RectSize = Vector2.new(GW, GH), Aspect = GW / GH,
        TightOffset = off + Vector2.new(t[1], t[2]), TightSize = Vector2.new(t[3], t[4]), TightAspect = t[3] / t[4],
        Kind = (id == "Knife") and "Melee" or "Gun", Key = id }
end

local function gearSpec(t: string): any?
    t = GEAR_ALIAS[t] or t
    local i = gearIndex[t]
    if not i then return nil end
    local img = ItemIcons.ATLAS[ItemIcons.GEAR_ATLAS]
    if not img or img == "" then return nil end
    local c = i - 1
    local off = Vector2.new((c % 4) * GEAR, ItemIcons.GEAR_TOP + (c // 4) * GEAR)
    return { Image = img, RectOffset = off, RectSize = Vector2.new(GEAR, GEAR), Aspect = 1,
        TightOffset = off, TightSize = Vector2.new(GEAR, GEAR), TightAspect = 1, Kind = "Gear", Key = t }
end

local itemData: any = nil
local function ID(): any
    if itemData == nil then
        local ok, m = pcall(function() return require(script.Parent:WaitForChild("ItemData", 5) :: any) end)
        itemData = ok and m or false
    end
    return itemData or nil
end

local function resolveString(s: string): any?
    local hit = cache[s]
    if hit ~= nil then return hit or nil end
    local spec = gunSpec(s) or gearSpec(s)
    if not spec then
        if s == "Weapon" or s == "Gun" then spec = gunSpec("AK47")
        elseif s == "Melee" then spec = gunSpec("Knife")
        else
            local D = ID()
            local b = D and D.BaseWeapons and D.BaseWeapons[s]
            if b then spec = gunSpec(CLASS_FALLBACK[b.Class or ""] or "AK47")
            elseif D and D.MeleeWeapons and D.MeleeWeapons[s] then spec = gunSpec("Knife") end
        end
    end
    if spec or ItemIcons.ATLAS[1] ~= "" then cache[s] = spec or false end
    return spec
end

function ItemIcons.For(x: any): any?
    if type(x) == "string" then return resolveString(x) end
    if type(x) ~= "table" then return nil end
    if x.Kind == "Melee" then return gunSpec("Knife") end
    if x.Slot or x.GearType then return gearSpec(x.GearType or x.Slot) end
    if x.Kind == "Gear" and x.Type then return gearSpec(x.Type) end
    local base = x.BaseId or x.Base
    if type(base) == "string" then return resolveString(base) end
    return nil
end

function ItemIcons.Apply(label: ImageLabel, x: any, full: boolean?): any?
    local spec = ItemIcons.For(x)
    if not spec then return nil end
    label.Image = spec.Image
    label.ImageRectOffset = full and spec.RectOffset or spec.TightOffset
    label.ImageRectSize = full and spec.RectSize or spec.TightSize
    label.ScaleType = Enum.ScaleType.Fit
    return spec
end

return ItemIcons
