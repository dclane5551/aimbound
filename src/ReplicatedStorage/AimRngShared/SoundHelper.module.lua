        s.SoundId = "rbxassetid://3650637614" -- Gun Kit SwitchSound, used as a dry-fire click
        s.PlaybackSpeed = 1.8; s.Volume = 0.5
    elseif soundType == "Click" then
        s.SoundId = "rbxasset://sounds/button.wav"
        s.PlaybackSpeed = 1.2; s.Volume = 0.3
    else
        s.SoundId = "rbxasset://sounds/button.wav"
        s.PlaybackSpeed = 1.2; s.Volume = 0.3
    end

    s.PlaybackSpeed *= jitter
    if HIT_TYPES[soundType] then s.Volume *= SoundHelper.HitVolume end

    if addPunch then
        local eq = Instance.new("EqualizerSoundEffect")
        eq.LowGain = 6
        eq.MidGain = -1
        eq.HighGain = -3
        eq.Parent = s
        local dist = Instance.new("DistortionSoundEffect")
        dist.Level = 0.12
        dist.Parent = s
    end
    if addRing then
        local rev = Instance.new("ReverbSoundEffect")
        rev.DecayTime = 1.4
        rev.Density = 0.6
        rev.Diffusion = 0.7
        rev.WetLevel = -4
        rev.Parent = s
    end

    return s
end

-- A couple of categories get a second, quieter layer underneath the primary clip -- a low "thud"
-- stacked under a "crack" reads as one fuller, punchier sound instead of one thin built-in clip.
local LAYER_UNDER: { [string]: { soundType: SoundType, volumeScale: number } } = {
    ShootShotgun = { soundType = "PumpAction", volumeScale = 0.7 },
    -- ShootLauncher used to layer BossSlam underneath -- two independently-EQ'd/distorted/reverbed
    -- sounds stacking made it needlessly loud and muddy ("makes no sense"). A single clean clip reads
    -- better than a hard-to-parse wall of noise.
    -- (v4: BossSlam no longer layers the old synth EnemyDeath under it -- game_slam carries its own debris)
    EnemyDeath = { soundType = "ShootHeavy", volumeScale = 0.45 },
}

local function BuildLayers(soundType: SoundType): { Sound }
    local sounds = { BuildSound(soundType) }
    local layer = LAYER_UNDER[soundType]
    if layer then
        local under = BuildSound(layer.soundType)
        under.Volume *= layer.volumeScale
        table.insert(sounds, under)
    end
    return sounds
end

-- Rate-limited, non-positional play (UI/weapon/player-centric cues). Behavior-identical call
-- signature to before -- only the sounds themselves got better.
-- ===== HIT SOUND POOL (owner: "the hitsounds are incredibly delayed") =====
-- Building a fresh Sound per hit meant it had to load before it could play. Hit / head-hit / kill sounds now come
-- from a small pool of pre-built, preloaded Sounds per choice: a hit just rewinds and plays one that's ready.
local hitPools: { [string]: { Sounds: { Sound }, Next: number } } = {}
local function PoolFor(soundType: string)
    local proto = BuildSound(soundType :: any) -- (resolves the current choice, clip, pitch and volume)
    local vol = proto.Volume
    local variant = (soundType == "HitCrit") and SoundHelper.HeadVariant or (soundType == "Kill") and SoundHelper.KillVariant or SoundHelper.HitVariant
    local key = soundType .. "|" .. proto.SoundId .. "|" .. tostring(variant) -- (not the jittered pitch)
    local pool = hitPools[key]
    if not pool then
        pool = { Sounds = {}, Next = 1 }
        for i = 1, 4 do
            local s = (i == 1) and proto or proto:Clone()
            s.Name = "HitPool_" .. soundType
            s.SoundGroup = MixGroup(soundType)
            s.Parent = SoundService
            pool.Sounds[i] = s
        end
        hitPools[key] = pool
        task.spawn(function() pcall(function() game:GetService("ContentProvider"):PreloadAsync(pool.Sounds) end) end)
    else
        proto:Destroy()
    end
    return pool, vol
end
-- Called by the client at startup and when a hit-sound setting changes, so the first hit is instant too.
function SoundHelper.WarmHits()
    for _, t in ipairs({ "HitNormal", "HitCrit", "Kill" }) do PoolFor(t) end
end

-- HIT CHAIN (0.49, owner: "make sounds more progressive, so for example hitsounds build up slowly in pitch as you hit
-- something continuously and reset upon missing. The buildup can be amplified / slowed depending on the firerate"):
-- every hit volley (all pellets of one trigger pull count once) raises the hit sound by STEP semitones, up to an octave;
-- a miss (or 1.5 s without a hit) starts it over. STEP = 5 / shots per second: a 1-shot/s sniper climbs 2 semitones a
-- hit (cap), a 12/s SMG ~0.4 -- every gun reaches the top after about the same time on target (~2.5 s).
SoundHelper.ChainRate = 5
SoundHelper.HitPitch = 1
local chain = { n = 0, lastHit = 0, missAt = nil :: number? }
local CHAIN_MAX = 12
function SoundHelper.ChainHit()
    local now = os.clock()
    local sameVolley = now - chain.lastHit < 0.02
    if chain.missAt and not sameVolley and chain.missAt > chain.lastHit and now - chain.missAt > 0.02 then chain.n = 0 end
    if now - chain.lastHit > 1.5 then chain.n = 0 end
    if not sameVolley then chain.n += 1 end
    chain.lastHit, chain.missAt = now, nil
    local step = math.clamp(5 / math.max(0.5, SoundHelper.ChainRate or 5), 0.35, 2)
    SoundHelper.HitPitch = 2 ^ (math.min(CHAIN_MAX, (chain.n - 1) * step) / 12)
end
function SoundHelper.ChainMiss()
    local now = os.clock()
    if now - chain.lastHit < 0.02 then return end -- (a stray pellet of a volley that hit)
    chain.missAt = now
end

-- (v4) per-sound minimum gap (MIN_GAP otherwise): the same click / success / coin can't stack on a double fire
local GAP = { Click = 0.05, Upgrade = 0.15, Craft = 0.15, Roll = 0.12, Coin = 0.1, Purchase = 0.2, PlayerHurt = 0.12 }
local REWARD = { LevelUp = true, Victory = true }
local function PlayInner(soundType: SoundType)
    local now = os.clock()
    local last = lastPlayed[soundType]
    if last and (now - last) < (GAP[soundType] or MIN_GAP) then return end
    -- REWARD CHANNEL (v4): one fanfare at a time (a level up landing with a floor clear plays one), and a small
    -- success / craft right after a fanfare is dropped
    if REWARD[soundType] then
        if now - (lastPlayed._reward or -9) < 0.9 then return end
        lastPlayed._reward = now
    elseif soundType == "Upgrade" or soundType == "Craft" then
        if now - (lastPlayed._reward or -9) < 0.5 then return end
    end
    lastPlayed[soundType] = now

    if soundType == "PlayerHurt" and (SoundHelper.Custom.PlayerHurt.Id or 0) == 0 then return end -- (no stand-in clip)
    if HIT_TYPES[soundType] then
        if soundType == "Kill" and SoundHelper.KillVariant == "Off" then return end
        -- (0.62, owner: "Hitsounds overlap (body or headshot) if you switch what youre shooting"): body + head hits share
        -- one channel -- one volley that lands both plays only the headshot, and a new hit cuts the OTHER kind's tail
        if soundType == "HitNormal" or soundType == "HitCrit" then
            local other = (soundType == "HitNormal") and "HitCrit" or "HitNormal"
            if soundType == "HitNormal" and lastPlayed.HitCrit and now - lastPlayed.HitCrit < 0.03 then return end
            for key, pl in pairs(hitPools) do
                if string.sub(key, 1, #other + 1) == other .. "|" then
                    for _, snd in ipairs(pl.Sounds) do if snd.IsPlaying then snd:Stop() end end
                end
            end
        end
        local pool, vol = PoolFor(soundType)
        local s = pool.Sounds[pool.Next]
        pool.Next = pool.Next % #pool.Sounds + 1
        s.Volume = vol -- (follows the Hit Sound Volume setting live)
        if s:GetAttribute("BaseSpeed") == nil then s:SetAttribute("BaseSpeed", s.PlaybackSpeed) end
        s.PlaybackSpeed = s:GetAttribute("BaseSpeed") * ((soundType ~= "Kill") and SoundHelper.HitPitch or 1)
        s.TimePosition = 0
        s:Play()
        return
    end

    local group = MixGroup(soundType)
    for _, s in ipairs(BuildLayers(soundType)) do
        s.SoundGroup = group
        s.Parent = SoundService
        s:Play()
        s.Ended:Connect(function() s:Destroy() end)
    end
end

-- Positional play: parents the Sound to a world Part (an enemy's torso, a projectile, a hazard)
-- so nearby players hear it louder than far-away ones, via the same RollOff settings as everything
-- else. Safe to call from server scripts -- it just creates/replicates a normal Sound instance.
-- No rate-limit table here on purpose: every caller passes a freshly-created, one-shot projectile
-- Part, never a shared/reused one, so there's nothing to de-duplicate against.
-- VOICE BUDGET (owner 2026-10-02: "the audio sometimes breaks after a boss and gets very loud"): bosses fire dozens
-- of area strikes at once, and every one used to start its own sound -- each with its own distortion + reverb. Stacked
-- that deep, Roblox's mixer clips (loud, crunchy) and can stay broken. Now: the same kind within AT_GAP is one sound,
-- at most AT_MAX world sounds play at once, and world sounds carry no per-sound distortion / reverb.
local AT_GAP, AT_MAX = 0.09, 14
-- (v4) roll-off per world sound { min, max studs }: strikes stay local, slams / blasts carry across an arena, a boss roar
-- reaches the whole room (default 10 / 150)
local ROLLOFF = { AreaStrike = { 6, 120 }, BossAttack = { 8, 160 }, BossSlam = { 12, 240 }, Explosion = { 12, 240 },
    BossRoar = { 25, 420 }, ShieldUp = { 8, 140 }, ShieldDown = { 8, 140 }, EliteAbility = { 8, 140 },
    GateOpen = { 40, 400 }, GateBeam = { 25, 250 }, WarpIn = { 12, 160 }, -- (the gate is the room's far door: heard across it)
    -- (ENEMY ATTACKS PILOT 2026-10-30: enemy rounds reuse the gun recordings at the shooter -- kept local so a room of gunners
    -- doesn't sound like your own gun; the marksman's crack + the shell's thump carry a little further)
    ShootPistol = { 5, 80 }, ShootSniper = { 8, 140 }, ShootHeavy = { 8, 120 }, Melee = { 5, 60 }, Dash = { 5, 70 }, AttackWarn = { 6, 110 } }
local lastAt, liveAt = {}, 0
local function PlayAtInner(soundType: SoundType, part: BasePart)
    if not part or not part.Parent then return end
    local now = os.clock()
    if (lastAt[soundType] and now - lastAt[soundType] < AT_GAP) or liveAt >= AT_MAX then return end
    lastAt[soundType] = now
    local group = MixGroup(soundType)
    for _, s in ipairs(BuildLayers(soundType)) do
        for _, fx in ipairs(s:GetChildren()) do
            if fx:IsA("DistortionSoundEffect") or fx:IsA("ReverbSoundEffect") then fx:Destroy() end
        end
        s.SoundGroup = group
        local ro = ROLLOFF[soundType]
        if ro then s.RollOffMinDistance, s.RollOffMaxDistance = ro[1], ro[2] end
        s.Parent = part
        liveAt += 1
        local done = false
        local function Release() if not done then done = true; liveAt -= 1 end end
        s.Ended:Connect(Release)
        s.Destroying:Connect(Release)
        s:Play()
        Debris:AddItem(s, 3.0)
    end
end

-- (v4) never throw: hit sounds are called BEFORE the hitmarker / damage numbers / kill effect in the client
function SoundHelper.Play(soundType: SoundType)
    local ok, err = pcall(PlayInner, soundType)
    if not ok then warn("[SoundHelper] " .. tostring(soundType) .. ": " .. tostring(err)) end
end
function SoundHelper.PlayAt(soundType: SoundType, part: BasePart)
    local ok, err = pcall(PlayAtInner, soundType, part)
    if not ok then warn("[SoundHelper] " .. tostring(soundType) .. ": " .. tostring(err)) end
end

-- A weapon's Class drives its stats/balance (e.g. the Hunter's Bow is Class="Sniper" because it's a
-- one-shot, long-range hitter), but that's not always the right SOUND for the weapon's theme -- a bow
-- shouldn't crack like a rifle. This lets a specific BaseId override the sound category regardless of
-- its gameplay Class, checked before the Class-based fallback below.
local BASEID_SOUND_OVERRIDE: { [string]: SoundType } = {
    ["HuntersBow"] = "ShootBow",
}

-- Maps a weapon's Class to a distinct fire-sound envelope so different guns actually sound
-- different, instead of every weapon in the game sharing one identical "Shoot" ping.
function SoundHelper.PlayWeaponFire(weaponClass: string?, baseId: string?)
    if baseId and BASEID_SOUND_OVERRIDE[baseId] then
        SoundHelper.Play(BASEID_SOUND_OVERRIDE[baseId])
        return
    end

    local category: SoundType = "ShootPistol"
    if weaponClass == "Shotgun" then
        category = "ShootShotgun"
    elseif weaponClass == "Sniper" then
        category = "ShootSniper"
    elseif weaponClass == "SMG" or weaponClass == "AssaultRifle" or weaponClass == "Rifle" or weaponClass == "Burst" then
        category = "ShootSMG"
    elseif weaponClass == "Laser" then
        category = "ShootLaser"
    elseif weaponClass == "Launcher" or weaponClass == "Explosive" then
        category = "ShootLauncher"
    elseif weaponClass == "Heavy" or weaponClass == "Minigun" then
        category = "ShootHeavy"
    end
    SoundHelper.Play(category)
end

return SoundHelper
