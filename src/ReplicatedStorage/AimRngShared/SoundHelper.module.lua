    s.Volume = 0.5
    s.RollOffMaxDistance = 150
    s.RollOffMode = Enum.RollOffMode.InverseTapered

    local custom = SoundHelper.Custom[soundType]
    if soundType == "HitNormal" then custom = SoundHelper.HitSounds[SoundHelper.HitVariant] or SoundHelper.HitSounds.Thock end
    if soundType == "HitCrit" then custom = SoundHelper.HitSounds[SoundHelper.HeadVariant] or SoundHelper.HitSounds.Dink end
    if soundType == "Kill" then custom = SoundHelper.KillSounds[SoundHelper.KillVariant] or (SoundHelper.KillVariant == "Pulse" and custom) or nil end
    if custom and custom.Id ~= 0 then
        local id, vol, pitch = SoundHelper.Resolve(custom)
        s.SoundId = "rbxassetid://" .. tostring(id)
        s.Volume = vol * (HIT_TYPES[soundType] and SoundHelper.HitVolume or 1)
