-- ===== FALLBACK RESOLVER (v4) =====
local idState: { [number]: string } = {} -- id -> "probing" | "ok" | "bad"
local ContentProvider = game:GetService("ContentProvider")
local function Probe(id: number)
    if idState[id] then return end
    idState[id] = "probing"
    task.spawn(function()
        local snd = Instance.new("Sound")
        snd.SoundId = "rbxassetid://" .. tostring(id)
        local status
        pcall(function() ContentProvider:PreloadAsync({ snd }, function(_, st) status = st end) end)
        snd:Destroy()
        idState[id] = (status == Enum.AssetFetchStatus.Success) and "ok" or "bad"
    end)
end
-- entry { Id, Volume, Old?, OldVolume?, OldPitch? } -> (id, volume, pitch): the new clip once it loads, else the old one
function SoundHelper.Resolve(entry: any): (number, number, number)
    if not entry then return 0, 0, 1 end
    if entry.Old and entry.Id ~= 0 then
        Probe(entry.Id)
        if idState[entry.Id] ~= "ok" then return entry.Old, entry.OldVolume or entry.Volume, entry.OldPitch or 1 end
    end
    return entry.Id, entry.Volume, 1
end
function SoundHelper.ProbeAll()
    for _, t in ipairs({ SoundHelper.Custom, SoundHelper.HitSounds, SoundHelper.KillSounds }) do
        for _, e in pairs(t) do if type(e) == "table" and e.Old and e.Id ~= 0 then Probe(e.Id) end end
    end
end
if game:GetService("RunService"):IsClient() then task.defer(SoundHelper.ProbeAll) end

local function BuildSound(soundType: SoundType): Sound
